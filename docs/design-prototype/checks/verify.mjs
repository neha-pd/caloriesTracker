import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const root={innerHTML:'',textContent:'',classList:{add(){},remove(){}}};
const context={document:{getElementById:()=>root,addEventListener(){},querySelector:()=>null},location:{hash:''},history:{replaceState(){}},setTimeout:()=>0,clearTimeout(){},console};
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('../dist/app.js',import.meta.url),'utf8'),context);
const run=code=>vm.runInContext(code,context);
const screens=run('ids.map(id=>({id,html:phone(id)}))');
assert.equal(screens.length,35);
assert.equal(new Set(screens.map(s=>crypto.createHash('sha256').update(s.html.replace(/data-screen="[^"]+"/,'')).digest('hex'))).size,35,'Every screen must render a distinct design');
for(const screen of screens){
 for(const [,destination] of screen.html.matchAll(/data-go="([^"]+)"/g)) assert(screens.some(s=>s.id===destination),`${screen.id} links to missing ${destination}`);
 for(const [,asset] of screen.html.matchAll(/src="(assets\/[^"]+)"/g)) assert(fs.existsSync(new URL('../dist/'+asset,import.meta.url)),`Missing ${asset}`);
}
run("ids.forEach(go);state.mode='gallery';render();state.mode='system';render();");
run("state.selectedFood='Banana';state.portion=2;state.meal='Dinner';handleAction('logFood');");
assert.equal(run('dayEnergy()'),1494,'Portion-adjusted food must update energy');
assert.equal(run('state.entries[0].calories'),210);
assert.equal(run('state.lastXp'),25);
assert.equal(run('state.screen'),'logged');
run("handleAction('logFood');");
assert.equal(run('state.lastXp'),0,'Repeat meal-slot logs must not farm XP');
run("handleAction('water');handleAction('water');");
assert.equal(run('state.water'),1750);
assert.equal(run('state.xp'),780,'Hydration XP must be awarded once');
run("handleAction('claim');handleAction('claim');");
assert.equal(run('state.xp'),790,'A quest cannot be claimed twice');
run("state.foodTab='All foods';state.query='banana';");
assert(run('searchResults()').includes('Banana'));
assert(!run('searchResults()').includes('Harvest chicken'));
run("state.query='unfindable';");assert(run('searchResults()').includes('No food found'));
run("handleForm('editGoals',new Map([['calories','2300'],['protein','140'],['carbs','270'],['fat','65']]));");
assert.equal(run('state.calories'),2300);
assert(run('screens.home()').includes('2,300'));
run("handleAction('resetDemo');");
assert.equal(run('dayEnergy()'),1284);
assert.equal(run('state.xp'),740);
assert.equal(run('state.entries.length'),0);
console.log('PASS: 35 distinct screens; all destinations and assets; gallery/system rendering; portion logging; energy totals; XP deduplication; water; search; editable targets; reset.');
